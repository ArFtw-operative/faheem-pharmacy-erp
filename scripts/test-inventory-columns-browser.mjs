import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const base = 'http://127.0.0.1:8025';
const browser = await chromium.launch({headless:true});
try {
 const page = await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[]; page.on('pageerror', e=>errors.push(e.message));
 await page.goto(base+'/login'); await page.fill('[name=username]','shortcut-test'); await page.fill('[name=password]','isolated-browser-test'); await page.click('button[type=submit]'); await page.waitForURL(u=>!u.pathname.startsWith('/login'));
 let response=await page.request.post(base+'/api/erp/inventory',{data:{name:'Inventory column test '+Date.now(),base_unit:'TABLET',pack_unit:'STRIP',units_per_pack:10,mrp:30}});
 assert.equal(response.ok(),true); const item=await response.json();
 response=await page.request.post(base+`/api/erp/inventory/${item.id}/adjust`,{data:{direction:'IN',quantity:20,batch_no:'COLTEST',expiry:'12/2099',mrp:30,reason:'Column browser test'}}); assert.equal(response.ok(),true,await response.text());
 await page.goto(base+'/app/inventory'); await page.locator('.f-q').fill('Inventory column test'); await page.locator('.b-title').filter({hasText:'Inventory column test'}).waitFor();
 assert.match(await page.locator('.products thead').innerText(),/Rate \/ pack/);
 const selection=await page.locator('.products tr.sel').getAttribute('data-i');
 await page.keyboard.press('Alt+c'); await page.getByRole('dialog',{name:'Inventory columns'}).waitFor();
 await page.locator('input[name=products][value=form]').uncheck();
 await page.locator('input[name=products][value=purchase_invoice]').check();
 await page.locator('input[name=batches][value=unit_purchase_rate]').check();
 await page.locator('input[name=batches][value=purchase_invoice]').check();
 await page.getByRole('button',{name:/^Apply/}).click();
 assert.equal(await page.locator('.products th[data-col=form]').count(),0);
 assert.equal(await page.locator('.products tr.sel').getAttribute('data-i'),selection);
 assert.equal(await page.locator('.batches th[data-col=unit_purchase_rate]').count(),1);
 assert.match(await page.locator('.batches tbody').innerText(),/30.00/);
 await page.reload(); await page.locator('.b-title').filter({hasText:'Inventory column test'}).waitFor();
 assert.equal(await page.locator('.products th[data-col=form]').count(),0);
 assert.equal(await page.locator('.batches th[data-col=unit_purchase_rate]').count(),1);
 await page.locator('.f-columns').click(); for (const box of await page.locator('input[name=products]').all()) await box.uncheck();
 await page.getByRole('button',{name:/^Apply/}).click();
 assert.match(await page.locator('.modal-error').innerText(),/at least one column/);
 await page.locator('[data-defaults=products]').click(); await page.locator('[data-defaults=batches]').click();
 await page.getByRole('button',{name:/^Apply/}).click();
 assert.equal(await page.locator('.products th[data-col=form]').count(),1);
 await page.screenshot({path:'/tmp/pharmacy-inventory-columns.png'});
 await page.keyboard.press('Alt+r'); await page.locator('[data-report=batch-stock]').click();
 await page.locator('[data-columns]').click();
 assert.equal(await page.locator('[name=column][value=purchase_rate]').count(),1);
 await page.locator('[name=column][value=purchase_rate]').check(); await page.locator('[name=column][value=pack_mrp]').check();
 await page.locator('[name=column][value=purchase_invoice]').check(); await page.getByRole('button',{name:'Apply',exact:true}).click();
 await page.keyboard.press('Alt+g'); await page.locator('.report-document').waitFor();
 assert.match(await page.locator('.report-table thead').innerText(),/Purchase Rate \/ pack/);
 await page.screenshot({path:'/tmp/pharmacy-inventory-report-prices.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS: inventory rates/MRP, product and batch column controls, keyboard access, saved selections, preserved selection, defaults, empty-selection validation and matching stock-report columns');
} finally {await browser.close();}
